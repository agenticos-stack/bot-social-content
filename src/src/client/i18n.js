/** Resolves a key for `locale`, substituting `{name}` tokens from `vars`. Falls back to English, then the key itself. */
export function t(locale, key, vars) {
  const table = STRINGS[locale] || STRINGS.en;
  const template = table[key] ?? STRINGS.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) => (Object.hasOwn(vars, name) ? String(vars[name]) : match));
}

/** Normalizes whatever `document.documentElement.lang` the host set to one of LOCALES. */
export function resolveLocale(lang) {
  return lang === "zh-HK" || lang === "zh-Hant-HK" || (typeof lang === "string" && lang.toLowerCase().startsWith("zh")) ? "zh-HK" : "en";
}
